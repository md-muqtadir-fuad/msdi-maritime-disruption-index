"""Merge batched LLM score files stored in ZIP archives.

By default, archives are read from
``data/03_processed/model_scores/scores_zips`` without extracting them. The
merged dataset and a JSON audit report are written beside that directory.
CSV, JSON Lines, and JSON members are supported.
"""

from __future__ import annotations

import argparse
import io
import json
import zipfile
from pathlib import Path

import pandas as pd


PROJECT_ROOT = Path(__file__).resolve().parents[1]
DEFAULT_INPUT = PROJECT_ROOT / "data/03_processed/model_scores/scores_zips"
DEFAULT_OUTPUT = PROJECT_ROOT / "data/03_processed/model_scores/llm_scores_merged.csv"
DEFAULT_EVENT_MAP = PROJECT_ROOT / (
    "data/03_processed/news_full_text/pre_llm_filter/event_dedup/"
    "canonical_event_article_map.csv"
)
EVENT_COLUMNS = [
    "event_day",
    *[
        f"{column}_{profile}"
        for profile in ("weekly", "monthly")
        for column in (
            "event_id",
            "event_cluster_size",
            "event_source_count",
            "event_span_days",
            "event_weight_fixed_total_descriptive",
            "event_weight_sqrt_descriptive",
        )
    ],
]
LEGACY_EVENT_COLUMNS = [
    "event_id",
    "event_cluster_size",
    "event_source_count",
    "event_span_days",
    "event_weight_fixed_total_descriptive",
    "event_weight_sqrt_descriptive",
]


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Merge LLM score files from ZIP archives.")
    parser.add_argument(
        "--input-dir",
        type=Path,
        action="append",
        dest="input_dirs",
        help="Directory containing ZIPs; repeat for multiple models. Searched recursively.",
    )
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument(
        "--id-column",
        default="article_id",
        help="Identifier used to detect conflicting repeated records.",
    )
    parser.add_argument(
        "--event-map",
        type=Path,
        default=DEFAULT_EVENT_MAP,
        help="Canonical pre-LLM article-to-event mapping generated by Stage 08.",
    )
    parser.add_argument(
        "--allow-missing-event-map",
        action="store_true",
        help="Legacy-only escape hatch; publication runs require the event map.",
    )
    return parser.parse_args()


def read_member(archive: zipfile.ZipFile, member: str) -> pd.DataFrame:
    suffix = Path(member).suffix.lower()
    raw = archive.read(member)
    if suffix == ".csv":
        return pd.read_csv(io.BytesIO(raw))
    if suffix in {".jsonl", ".ndjson"}:
        return pd.read_json(io.BytesIO(raw), lines=True)
    if suffix == ".json":
        value = json.loads(raw.decode("utf-8-sig"))
        if isinstance(value, dict):
            for key in ("results", "records", "data", "items"):
                if isinstance(value.get(key), list):
                    value = value[key]
                    break
        if not isinstance(value, list):
            raise ValueError("JSON must be a record list or contain results/records/data/items")
        return pd.DataFrame(value)
    raise ValueError(f"Unsupported file type: {suffix}")


def is_score_member(member: str) -> bool:
    """Return true only for final article-level score tables, not ZIP diagnostics."""
    name = Path(member).name.lower()
    return (
        (name.startswith("scored_chunk_") and name.endswith(".csv"))
        or ("article_level_scores_valid" in name and name.endswith(".csv"))
    )


def merge_archives(input_dirs: list[Path], id_column: str) -> tuple[pd.DataFrame, pd.DataFrame, dict]:
    archives = sorted(
        {archive.resolve() for directory in input_dirs for archive in directory.rglob("*.zip")},
        key=lambda path: str(path).lower(),
    )
    if not archives:
        searched = ", ".join(str(path) for path in input_dirs)
        raise FileNotFoundError(f"No ZIP files found under: {searched}")

    frames: list[pd.DataFrame] = []
    errors: list[dict[str, str]] = []
    members_read = 0
    for archive_path in archives:
        with zipfile.ZipFile(archive_path) as archive:
            for member in sorted(archive.namelist()):
                if not is_score_member(member):
                    continue
                try:
                    frame = read_member(archive, member)
                    frame["_source_zip"] = archive_path.name
                    frame["_source_file"] = member
                    frame["_source_row"] = range(1, len(frame) + 1)
                    frames.append(frame)
                    members_read += 1
                except Exception as exc:  # continue so one bad member does not lose a batch
                    errors.append({"zip": archive_path.name, "member": member, "error": str(exc)})

    if not frames:
        raise ValueError("ZIP files contained no recognized final score tables")

    combined = pd.concat(frames, ignore_index=True, sort=False)
    source_columns = ["_source_zip", "_source_file", "_source_row"]
    value_columns = [column for column in combined.columns if column not in source_columns]
    rows_before = len(combined)
    combined = combined.drop_duplicates(subset=value_columns, keep="first").reset_index(drop=True)

    conflicts = pd.DataFrame()
    key_columns = [id_column]
    if "model_name" in combined.columns:
        key_columns.insert(0, "model_name")
    if id_column in combined.columns:
        ids = combined[id_column].astype("string").str.strip()
        valid_id = ids.notna() & ids.ne("")
        repeated = valid_id & combined.duplicated(subset=key_columns, keep=False)
        conflicts = combined.loc[repeated].sort_values(key_columns, kind="stable")

    audit = {
        "input_directories": [str(path) for path in input_dirs],
        "archives_found": len(archives),
        "members_read": members_read,
        "rows_before_exact_deduplication": rows_before,
        "exact_duplicate_rows_removed": rows_before - len(combined),
        "merged_rows": len(combined),
        "columns": list(combined.columns),
        "id_column": id_column,
        "record_key": key_columns,
        "rows_with_conflicting_repeated_ids": len(conflicts),
        "read_errors": errors,
    }
    return combined, conflicts, audit


def enrich_with_event_map(
    scores: pd.DataFrame,
    event_map_path: Path,
    id_column: str,
) -> tuple[pd.DataFrame, dict]:
    """Attach authoritative weekly/monthly pre-LLM event maps to every score row."""
    event_map = pd.read_csv(event_map_path, low_memory=False)
    required = [id_column, *EVENT_COLUMNS]
    missing = [column for column in required if column not in event_map.columns]
    if missing:
        raise ValueError(f"Event map lacks required columns: {missing}")
    event_map = event_map[required].copy()
    event_map[id_column] = event_map[id_column].astype("string").str.strip()
    if event_map[id_column].isna().any() or event_map[id_column].eq("").any():
        raise ValueError("Event map contains blank article IDs")
    if event_map.duplicated(id_column).any():
        raise ValueError("Event map must contain exactly one row per article ID")
    for profile in ("weekly", "monthly"):
        column = f"event_id_{profile}"
        if event_map[column].isna().any() or event_map[column].astype(str).str.strip().eq("").any():
            raise ValueError(f"Event map contains blank {profile} event IDs")

    output = scores.copy()
    output[id_column] = output[id_column].astype("string").str.strip()
    # Score exports may copy old event columns.  Always replace them from the
    # frozen Stage-08 map to guarantee the same mapping across all models.
    output = output.drop(
        columns=[
            column
            for column in (*EVENT_COLUMNS, *LEGACY_EVENT_COLUMNS)
            if column in output.columns
        ]
    )
    output = output.merge(event_map, on=id_column, how="left", validate="many_to_one")
    missing_assignment = output[["event_id_weekly", "event_id_monthly"]].isna().any(axis=1)
    if missing_assignment.any():
        examples = output.loc[missing_assignment, id_column].drop_duplicates().head(10).tolist()
        raise ValueError(
            f"{int(missing_assignment.sum())} score rows lack canonical event assignments; "
            f"sample article IDs={examples}"
        )
    audit = {
        "path": str(event_map_path.resolve()),
        "mapping_rows": int(len(event_map)),
        "mapping_events_weekly": int(event_map["event_id_weekly"].nunique()),
        "mapping_events_monthly": int(event_map["event_id_monthly"].nunique()),
        "score_rows_enriched": int(len(output)),
        "score_articles_enriched": int(output[id_column].nunique()),
        "score_rows_missing_event": 0,
        "authoritative_columns": EVENT_COLUMNS,
    }
    return output, audit


def main() -> None:
    args = parse_args()
    input_dirs = args.input_dirs or [DEFAULT_INPUT]
    input_dirs = [path.resolve() for path in input_dirs]
    merged, conflicts, audit = merge_archives(input_dirs, args.id_column)

    event_map_path = args.event_map.resolve()
    if event_map_path.is_file():
        merged, event_audit = enrich_with_event_map(merged, event_map_path, args.id_column)
        audit["canonical_event_mapping"] = event_audit
    elif args.allow_missing_event_map:
        audit["canonical_event_mapping"] = {
            "path": str(event_map_path),
            "status": "missing_explicitly_allowed_legacy_only",
        }
    else:
        raise FileNotFoundError(
            f"Canonical event map not found: {event_map_path}. Run Stage 08 first, "
            "or use --allow-missing-event-map only for a non-publication legacy merge."
        )

    output = args.output.resolve()
    output.parent.mkdir(parents=True, exist_ok=True)
    merged.to_csv(output, index=False)

    conflict_path = output.with_name(f"{output.stem}_conflicts.csv")
    audit_path = output.with_name(f"{output.stem}_audit.json")
    if not conflicts.empty:
        conflicts.to_csv(conflict_path, index=False)
    audit["output_file"] = str(output)
    audit["conflicts_file"] = str(conflict_path) if not conflicts.empty else None
    audit_path.write_text(json.dumps(audit, indent=2), encoding="utf-8")

    print(f"Merged {audit['merged_rows']:,} rows into {output}")
    print(f"Audit: {audit_path}")
    if not conflicts.empty:
        print(f"Warning: {len(conflicts):,} rows have repeated {args.id_column}; see {conflict_path}")


if __name__ == "__main__":
    main()
